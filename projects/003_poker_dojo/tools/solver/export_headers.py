"""Write the solver results as constexpr C++ tables (no dynamic memory) for the GBA game."""

import os

import numpy as np

from hands import CLASS_COMBOS, CLASS_NAMES

INCLUDE_DIR = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "include"))

CLASS_DOC = """\
    // Starting-hand class index 0..168: the classic 13x13 matrix, rows and columns ordered A, K, Q, ..., 2
    // (position 0 = A, 12 = 2); index = row * 13 + col.
    //   row == col: pocket pair (AA = 0, KK = 14, ..., 22 = 168)
    //   col >  row: suited, above the diagonal (AKs = 1, AQs = 2, ..., 32s = 155)
    //   row >  col: offsuit, below the diagonal (AKo = 13, ..., 32o = 167)
    // Card ranks elsewhere use 0..12 = 2..A (poker_cards.h); class_index() converts."""

COMMON = """\
#ifndef POKER_TABLES_CLASSES
#define POKER_TABLES_CLASSES

{doc}
    constexpr int class_count = 169;

    // rank_a, rank_b: 0..12 = 2..A. suited is ignored for pairs.
    [[nodiscard]] constexpr int class_index(int rank_a, int rank_b, bool suited)
    {{
        int hi = rank_a > rank_b ? rank_a : rank_b;
        int lo = rank_a > rank_b ? rank_b : rank_a;
        int row = 12 - hi;
        int col = 12 - lo;

        if(hi == lo)
        {{
            return row * 13 + row;
        }}

        return suited ? row * 13 + col : col * 13 + row;
    }}

    // Number of card combos of each class (6 pairs, 4 suited, 12 offsuit; total 1326).
    [[nodiscard]] constexpr int class_combos(int class_idx)
    {{
        int row = class_idx / 13;
        int col = class_idx % 13;
        return row == col ? 6 : (col > row ? 4 : 12);
    }}

    // Class names ("AA", "AKs", "AKo"...), indexed by class.
    constexpr const char* class_names[class_count] = {{
{names}
    }};

#endif
"""


def _names_block():
    lines = []
    for r in range(13):
        lines.append("        " + " ".join(f'"{CLASS_NAMES[r * 13 + c]}",' for c in range(13)))
    return "\n".join(lines)


def _array(values, per_line=13, indent=12):
    vals = [str(int(v)) for v in values]
    pad = " " * indent
    return "\n".join(pad + ", ".join(vals[i:i + per_line]) + "," for i in range(0, len(vals), per_line))


def _table3(name, ctype, data, stacks, variants, comment):
    lines = [f"    // {comment}", f"    constexpr {ctype} {name}[pushfold_variant_count][pushfold_stack_count][class_count] = {{"]
    for v in range(data.shape[0]):
        lines.append(f"        {{ // {variants[v][0]}")
        for s in range(data.shape[1]):
            lines.append(f"        {{ // {stacks[s]:g} bb")
            lines.append(_array(data[v, s]))
            lines.append("        },")
        lines.append("        },")
    lines.append("    };")
    return "\n".join(lines)


def _guard(name):
    return name.upper().replace(".", "_")


def write_pushfold(res, stacks, variants):
    path = os.path.join(INCLUDE_DIR, "poker_tables_pushfold.h")
    push = np.clip(np.rint(res["push"] * 255), 0, 255).astype(np.int64)
    call = np.clip(np.rint(res["call"] * 255), 0, 255).astype(np.int64)
    evp = np.clip(np.rint(res["ev_push"] * 100), -32768, 32767).astype(np.int64)
    evc = np.clip(np.rint(res["ev_call"] * 100), -32768, 32767).astype(np.int64)
    halves = [int(round(s * 2)) for s in stacks]
    expl = float(res["expl"].max())
    body = [
        "// GENERATED by tools/solver/solve.py - do not edit by hand.",
        "// Heads-up No-Limit Hold'em push/fold Nash equilibrium (SB shoves or folds, BB calls or folds), CFR+ on",
        "// the 169 classes weighted by combos with card removal. Exact all-in equities. Blinds 0.5 / 1 bb.",
        "// Variant 0: no ante. Variant 1: each player also posts a 0.1 bb ante (dead money) from the same stack.",
        "// Effective stack S counts everything a player has before posting. EVs are in hundredths of a bb.",
        f"// Max exploitability (NashConv, both players) over all tables: {expl:.1e} bb per hand.",
        "",
        "#ifndef POKER_TABLES_PUSHFOLD_H",
        "#define POKER_TABLES_PUSHFOLD_H",
        "",
        "#include <cstdint>",
        "",
        "namespace poker",
        "{",
        COMMON.format(doc=CLASS_DOC, names=_names_block()),
        f"    constexpr int pushfold_variant_count = {len(variants)}; // 0 = no ante, 1 = ante 0.1 bb per player",
        f"    constexpr int pushfold_stack_count = {len(stacks)};",
        "",
        "    // Effective stack of each table row, in half big blinds (2 = 1 bb ... 50 = 25 bb).",
        "    constexpr uint8_t pushfold_stack_halves[pushfold_stack_count] = {",
        _array(halves, per_line=25, indent=8),
        "    };",
        "",
        "    // Row of the nearest table stack (rounds to 0.5 bb, clamps to 1..25 bb). stack_halves = stack * 2.",
        "    [[nodiscard]] constexpr int pushfold_stack_index(int stack_halves)",
        "    {",
        f"        int i = stack_halves - {halves[0]};",
        "        return i < 0 ? 0 : (i >= pushfold_stack_count ? pushfold_stack_count - 1 : i);",
        "    }",
        "",
        _table3("sb_push_freq", "uint8_t", push, stacks, variants,
                "SB push frequency per class: 0 = always fold, 255 = always push."),
        "",
        _table3("bb_call_freq", "uint8_t", call, stacks, variants,
                "BB call frequency per class facing a push: 0 = always fold, 255 = always call."),
        "",
        _table3("sb_push_ev", "int16_t", evp, stacks, variants,
                "SB EV(push) - EV(fold) in 1/100 bb against the Nash BB. > 0: pushing is right; "
                "a fold costs this much."),
        "",
        _table3("bb_call_ev", "int16_t", evc, stacks, variants,
                "BB EV(call) - EV(fold) in 1/100 bb facing the Nash SB push range (given the SB pushed)."),
        "}",
        "",
        "#endif",
        "",
    ]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(body))
    return path


def write_equity(eq):
    path = os.path.join(INCLUDE_DIR, "poker_tables_equity.h")
    e = np.clip(np.rint(eq * 10000), 0, 10000).astype(np.int64)
    lines = [
        "// GENERATED by tools/solver/solve.py - do not edit by hand.",
        "// Exact preflop all-in equity of class a against class b (heads-up, ties count half), averaged over every",
        "// pair of combos with no shared card and every board. Units: 1/10000 (5000 = 50.00 %).",
        "// equity[a][b] + equity[b][a] = 10000 (up to rounding). Class index: see poker_tables_pushfold.h.",
        "",
        "#ifndef POKER_TABLES_EQUITY_H",
        "#define POKER_TABLES_EQUITY_H",
        "",
        "#include <cstdint>",
        "",
        "namespace poker",
        "{",
        COMMON.format(doc=CLASS_DOC, names=_names_block()),
        "    constexpr uint16_t preflop_equity[class_count][class_count] = {",
    ]
    for a in range(169):
        lines.append(f"        {{ // {CLASS_NAMES[a]}")
        lines.append(_array(e[a]))
        lines.append("        },")
    lines += ["    };", "}", "", "#endif", ""]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    return path


def write_all(eq, res, stacks, variants):
    assert int(CLASS_COMBOS.sum()) == 1326
    return [write_pushfold(res, stacks, variants), write_equity(eq)]
